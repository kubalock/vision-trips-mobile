<?php
declare(strict_types=1);

namespace VisionTrips\Frontend;

use VisionTrips\Airtable\Client;
use VisionTrips\Airtable\FieldMap;
use VisionTrips\Domain\Atol;
use VisionTrips\Domain\Theme;
use VisionTrips\Domain\Trip;
use VisionTrips\Security\Access;
use VisionTrips\Security\Token;
use VisionTrips\Settings;
use VisionTrips\Support\Dates;
use VisionTrips\Support\Str;

/**
 * Print-first documents rendered from the same Trip object as the experience. Each document is a standalone
 * A4 page with the member's branding; the browser print dialog produces the PDF.
 */
final class Documents
{
    public function __construct(private Trip $trip, private string $token, private bool $isAgent, private int $level)
    {
    }

    public function render(string $doc, string $arg): string
    {
        $doc = $doc !== '' ? $doc : 'index';
        $base = $this->base();
        switch ($doc) {
            case 'index':
                return View::render('documents/index', $base);
            case 'confirmation':
                return View::render('documents/confirmation', $base + ['atol' => Atol::build($this->trip)]);
            case 'invoice':
                return View::render('documents/invoice', $base + ['invoiceNo' => 'INV-' . preg_replace('/[^A-Za-z0-9\-]/', '', $this->trip->ref), 'issued' => Dates::now()->format('d/m/Y')]);
            case 'receipts':
            case 'receipt':
                $payment = null;
                foreach ($this->trip->payments as $p) {
                    if ($p->id === $arg) {
                        $payment = $p;
                    }
                }
                if ($arg !== '' && $payment === null) {
                    return View::render('states/plain', ['title' => 'Receipt not found', 'message' => 'That receipt does not exist on this booking.', 'status' => 404]);
                }
                return View::render('documents/receipt', $base + ['payment' => $payment]);
            case 'wallet':
                return View::render('documents/wallet', $base);
            case 'wallet':
                return View::render('documents/wallet', $base);
            case 'guarantee':
                if (!$this->trip->protection->isTta) {
                    return View::render('states/plain', ['title' => 'Not applicable', 'message' => 'This certificate is issued for Travel Trust Association members only.', 'status' => 404]);
                }
                return View::render('documents/guarantee', $base);
            case 'atol':
                $atol = Atol::build($this->trip);
                if (!$atol->applies || !$this->trip->atolCertificateAvailable()) {
                    return View::render('states/plain', ['title' => 'No ATOL certificate', 'message' => 'ATOL protection does not apply to this booking, so there is no certificate to show. Your financial protection details are on your booking page.', 'status' => 200]);
                }
                return View::render('documents/atol', $base + ['atol' => $atol]);
            case 'letter':
                if (!$this->isAgent) {
                    return View::render('states/plain', ['title' => 'Agent document', 'message' => 'Letters are generated by your travel agent. If you were sent this link, please ask them to resend it.', 'status' => 403]);
                }
                return View::render('documents/letter', $base + $this->letterData());
            case 'print':
                if (!$this->isAgent) {
                    return View::render('states/plain', ['title' => 'Agent document', 'message' => 'This summary is for your travel agent.', 'status' => 403]);
                }
                return View::render('documents/frontfile', $base);
        }
        return View::render('states/plain', ['title' => 'Document not found', 'message' => 'We do not have a document called "' . Str::clean($doc) . '".', 'status' => 404]);
    }

    /** @return array<string,mixed> */
    private function base(): array
    {
        $trip = $this->trip;
        $spec = Theme::spec($trip->theme);
        return [
            'trip'     => $trip,
            'brand'    => $trip->brand,
            'token'    => $this->token,
            'isAgent'  => $this->isAgent,
            'verified' => $this->level >= Access::LEVEL_KNOWLEDGE || $this->isAgent,
            'accent'   => $trip->brand->colour !== '' ? $trip->brand->colour : '#1F4F6E',
            'fontsUrl' => Theme::fontsUrl($trip->theme, $trip->brand->fontDisplay, $trip->brand->fontBody),
            'displayFont' => $trip->brand->fontDisplay !== '' ? $trip->brand->fontDisplay : $spec['family'],
            'bodyFont' => $trip->brand->fontBody !== '' ? $trip->brand->fontBody : 'Instrument Sans',
            'back'     => Token::url($this->token),
            'urls'     => ['confirmation' => Token::url($this->token, 'documents/confirmation'), 'invoice' => Token::url($this->token, 'documents/invoice'), 'atol' => Token::url($this->token, 'documents/atol'), 'receipts' => Token::url($this->token, 'documents/receipts'), 'letter' => Token::url($this->token, 'documents/letter'), 'print' => Token::url($this->token, 'documents/print')],
            'issuedOn' => Dates::now()->format('l j F Y'),
            'showDob'  => Settings::bool('show_dob'),
            'propositionLogo' => self::propositionLogo($trip->brand->propositionKey()),
        ];
    }

    public static function propositionLogo(string $key): string
    {
        return match ($key) {
            'worldchoice_plus' => 'https://my-trip.co.uk/wp-content/uploads/2025/11/WCPlus.png',
            'worldchoice' => 'https://my-trip.co.uk/wp-content/uploads/2025/11/WC.png',
            'tta' => 'https://my-trip.co.uk/wp-content/uploads/2025/11/TTA.png',
            'global' => 'https://my-trip.co.uk/wp-content/uploads/2025/11/Global.png',
            default => '',
        };
    }

    /** Letter templates (rich text) for the brand, fetched on demand (agent only). @return array<string,mixed> */
    private function letterData(): array
    {
        $templates = [];
        $ids = array_map(static fn ($t) => $t['id'], $this->trip->brand->letterTemplates);
        if ($ids) {
            $records = (new Client())->byIds($this->trip->base, FieldMap::table('brand_templates'), $ids);
            foreach ($records as $r) {
                $f = $r['fields'] ?? [];
                $letter = Str::clean(FieldMap::pick($f, 'brand_template', 'letter'));
                if ($letter === '') {
                    continue;
                }
                $templates[] = ['id' => (string) $r['id'], 'name' => Str::clean(FieldMap::pick($f, 'brand_template', 'name')) ?: 'Letter', 'html' => Str::richText(self::mergeFields($letter, $this->trip))];
            }
        }
        $selected = isset($_GET['comm']) ? preg_replace('/[^A-Za-z0-9]/', '', (string) $_GET['comm']) : '';
        return ['templates' => $templates, 'selected' => $selected, 'today' => Dates::now()->format('j F Y')];
    }

    /** Simple {{merge}} fields in letter templates. */
    public static function mergeFields(string $text, Trip $trip): string
    {
        $map = [
            '{{first_name}}' => $trip->leadFirstName(),
            '{{full_name}}' => $trip->lead ? $trip->lead->name : '',
            '{{booking_ref}}' => $trip->ref,
            '{{trip_name}}' => $trip->name,
            '{{departure_date}}' => Dates::long($trip->departs),
            '{{return_date}}' => Dates::long($trip->returns),
            '{{total}}' => $trip->money($trip->total),
            '{{balance}}' => $trip->money($trip->balance),
            '{{balance_due}}' => Dates::long($trip->balanceDueDate),
            '{{brand}}' => $trip->brand->name,
            '{{agent}}' => $trip->agentName,
        ];
        return strtr($text, $map);
    }
}
